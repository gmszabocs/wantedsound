// A deterministic shuffle makes the selection identical for every visitor.
(() => {
  const catalog = window.WANTED_CATALOG.slice().sort((left, right) =>
    left.url < right.url ? -1 : left.url > right.url ? 1 : 0
  );
  const selectionSize = Math.min(4, catalog.length);
  if (!selectionSize) {
    window.WANTED_PLAYLIST = [];
    return;
  }

  const monthsPerRound = Math.ceil(catalog.length / selectionSize);
  const catalogKey = catalog.map(track => track.url).join('|');
  const monthFormatter = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/Budapest',
    year: 'numeric',
    month: '2-digit'
  });
  let activeMonth = '';

  function shuffleRound(round) {
    const key = `wanted-sound-monthly-v1|${catalogKey}|${round}`;
    let seed = 2166136261;
    for (let index = 0; index < key.length; index += 1) {
      seed = Math.imul(seed ^ key.charCodeAt(index), 16777619);
    }

    function random() {
      seed = (seed + 0x6D2B79F5) >>> 0;
      let value = Math.imul(seed ^ (seed >>> 15), seed | 1);
      value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
      return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
    }

    const shuffled = catalog.slice();
    for (let index = shuffled.length - 1; index > 0; index -= 1) {
      const other = Math.floor(random() * (index + 1));
      [shuffled[index], shuffled[other]] = [shuffled[other], shuffled[index]];
    }
    return shuffled;
  }

  function selectMonth(date) {
    const parts = monthFormatter.formatToParts(date);
    const year = Number(parts.find(part => part.type === 'year').value);
    const month = Number(parts.find(part => part.type === 'month').value);
    const monthNumber = year * 12 + month - 1;
    const round = Math.floor(monthNumber / monthsPerRound);
    const offset = (monthNumber % monthsPerRound) * selectionSize;
    const shuffled = shuffleRound(round);

    // Keep the final group unchanged so it can be reconstructed independently.
    // Move any of last round's final picks out of this round's first group.
    // With twenty recordings, neighbouring months never repeat a recording.
    const previousFinalPicks = new Set(
      shuffleRound(round - 1).slice(-selectionSize).map(track => track.url)
    );
    for (let index = 0; index < selectionSize; index += 1) {
      if (!previousFinalPicks.has(shuffled[index].url)) continue;
      const replacement = shuffled.findIndex((track, position) =>
        position >= selectionSize &&
        position < shuffled.length - selectionSize &&
        !previousFinalPicks.has(track.url)
      );
      if (replacement !== -1) {
        [shuffled[index], shuffled[replacement]] = [shuffled[replacement], shuffled[index]];
      }
    }

    const tracks = Array.from({ length: selectionSize }, (_, index) =>
      shuffled[(offset + index) % shuffled.length]
    );
    return { month: `${year}-${String(month).padStart(2, '0')}`, tracks };
  }

  function refreshSelection() {
    const selection = selectMonth(new Date());
    if (selection.month === activeMonth) return;
    activeMonth = selection.month;
    window.WANTED_PLAYLIST = selection.tracks;
    window.dispatchEvent(new CustomEvent('wanted:playlistchange', { detail: selection }));
  }

  refreshSelection();
  setInterval(refreshSelection, 60 * 1000);
  window.addEventListener('pageshow', refreshSelection);
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden) refreshSelection();
  });
})();
